PERSIAN_DIGITS = str.maketrans("0123456789,", "۰۱۲۳۴۵۶۷۸۹٬")


def translate(language: str, key: str, **values) -> str:
    return STRINGS[key][language == "en"].format(**values)


def number(language: str, value: int) -> str:
    result = format(value, ",")
    return result.translate(PERSIAN_DIGITS) if language == "fa" else result
